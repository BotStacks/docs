"""Decide whether a merged pull request can affect public documentation.

Internal refactors, tests, dependency bumps, and observability work are
ignored unless the title or paths describe customer-facing behavior.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from docs_agent.models import PullRequest

_IGNORE_TITLE = re.compile(
    r"(?i)^(\s*(\[?(chore|deps|dependabot|ci|build|test|style|refactor)\]?)\b|bump\b|enable sentry|sentry )"
)
_IGNORE_PATH = re.compile(
    r"(?i)(^|/)(tests?|__tests__|fixtures)/|test_.*\.py$|_test\.py$|\.spec\.[jt]sx?$|"
    r"\.(lock|snap)$|package-lock\.json$|yarn\.lock$|"
    r"^\.github/|"
    r"(^|/)docs/(4\d|5\d|6\d)-|"
    r"alembic/|migrations/"
)
# Dependabot never changes product behavior. Other bots do: the Staging
# promotion pull request is opened by github-actions and is how a batch
# reaches main. That one must not be dropped just because the author is a bot.
_BOT_AUTHOR = re.compile(r"(?i)dependabot")

# Customer-facing topics the public docs already cover, plus the product
# areas the agent is allowed to consider.
_KEYWORDS = (
    "brain vault",
    "brainvault",
    "knowledge source",
    "knowledge base",
    "crawler",
    "site crawl",
    "autobuilder",
    "auto builder",
    "auto-builder",
    "dirtbox",
    "dirt box",
    "sequence studio",
    "widget",
    "embed",
    "activation kit",
    "chatbot",
    "installation",
    "install the",
    "godaddy", "airo",
    "bubble",
    "webflow",
    "wix",
    "squarespace",
    "slack",
    "discord",
    "whatsapp",
    "crisp",
    "file upload",
    "pdf",
    "docx",
    "csv",
    "markdown",
    "troubleshooting",
    "error message",
)

_PATH_HINTS = (
    "crawler",
    "knowledge",
    "brainvault",
    "file_extract",
    "content_extract",
    "dirtbox",
    "widget",
    "install-method",
    "embed",
    "integration",
    "godaddy", "airo",
    "bubble",
    "webflow",
    "activation",
)


@dataclass(frozen=True)
class Relevance:
    relevant: bool
    reason: str


def assess(pr: PullRequest) -> Relevance:
    if pr.base != "main":
        return Relevance(False, "not merged to main")
    if pr.head.startswith("docs-agent/") or "docs-agent" in pr.labels:
        return Relevance(False, "generated by the docs agent")
    if _BOT_AUTHOR.search(pr.author or ""):
        return Relevance(False, "automation author")
    title = pr.title or ""
    if _IGNORE_TITLE.search(title):
        return Relevance(False, "maintenance change")

    files = [item.filename for item in pr.files]
    customer_files = [name for name in files if not _IGNORE_PATH.search(name)]
    if files and not customer_files:
        return Relevance(False, "tests, lockfiles, or internal-only paths")

    haystack = " ".join([title, pr.body or "", *customer_files]).lower()
    if any(keyword in haystack for keyword in _KEYWORDS):
        return Relevance(True, "customer-facing topic")
    if any(hint in haystack for hint in _PATH_HINTS):
        return Relevance(True, "customer-facing path")
    return Relevance(False, "no documented product behavior")

